create or replace function public.create_booking(
  p_equipment_id bigint,
  p_start_at timestamptz,
  p_end_at timestamptz,
  p_purpose text default ''
)
returns jsonb
language plpgsql
security definer
set search_path = public, auth
as $$
declare
  v_user_id uuid := auth.uid();
  v_profile public.profiles%rowtype;
  v_booking_id uuid;
  v_local_day date;
  v_has_conflict boolean;
begin
  if v_user_id is null then
    raise exception 'not authenticated';
  end if;

  select * into v_profile from public.profiles where id = v_user_id;
  if v_profile.id is null or v_profile.status <> 'approved' then
    raise exception 'not approved';
  end if;

  if p_end_at <= p_start_at then
    raise exception '结束时间必须晚于开始时间';
  end if;

  if (p_start_at at time zone 'Asia/Shanghai')::date <>
     (((p_end_at - interval '1 microsecond') at time zone 'Asia/Shanghai')::date) then
    raise exception '预约必须位于同一天内';
  end if;

  if (p_end_at - p_start_at) > interval '24 hours' then
    raise exception '单次预约不能超过 24 小时';
  end if;

  if not exists (select 1 from public.equipment where id = p_equipment_id and active = true) then
    raise exception '设备不存在或已停用';
  end if;

  v_local_day := (p_start_at at time zone 'Asia/Shanghai')::date;
  perform pg_advisory_xact_lock(hashtext(p_equipment_id::text || ':' || v_local_day::text));

  select exists (
    select 1
    from public.reservations r
    where r.equipment_id = p_equipment_id
      and r.status in ('booked', 'in_use')
      and tstzrange(r.start_at, r.end_at, '[)') && tstzrange(p_start_at, p_end_at, '[)')
  ) into v_has_conflict;

  if v_has_conflict then
    raise exception '该设备在所选时间段已有预约';
  end if;

  insert into public.reservations (
    user_id, equipment_id, start_at, end_at, purpose, status, booked_by_name, booked_by_email
  ) values (
    v_user_id, p_equipment_id, p_start_at, p_end_at, coalesce(p_purpose, ''), 'booked',
    coalesce(v_profile.display_name, v_profile.email, ''), coalesce(v_profile.email, '')
  ) returning id into v_booking_id;

  return jsonb_build_object('id', v_booking_id);
end;
$$;

create or replace function public.cancel_booking(p_booking_id uuid)
returns void
language plpgsql
security definer
set search_path = public, auth
as $$
declare
  v_user_id uuid := auth.uid();
  v_booking public.reservations%rowtype;
begin
  select * into v_booking from public.reservations where id = p_booking_id for update;
  if v_booking.id is null then
    raise exception '预约不存在';
  end if;
  if v_booking.user_id <> v_user_id and not public.is_admin() then
    raise exception 'not authorized';
  end if;
  if v_booking.status not in ('booked', 'in_use') then
    raise exception '当前状态不能取消';
  end if;
  update public.reservations
  set status = 'cancelled', cancelled_at = now(), cancelled_by = v_user_id
  where id = p_booking_id;
end;
$$;

create or replace function public.start_usage(p_booking_id uuid)
returns void
language plpgsql
security definer
set search_path = public, auth
as $$
declare
  v_booking public.reservations%rowtype;
  v_user_id uuid := auth.uid();
begin
  select * into v_booking from public.reservations where id = p_booking_id for update;
  if v_booking.id is null then
    raise exception '预约不存在';
  end if;
  if v_booking.user_id <> v_user_id and not public.is_admin() then
    raise exception 'not authorized';
  end if;
  if v_booking.status <> 'booked' then
    raise exception '只有已预约状态可以开始使用';
  end if;
  if now() < v_booking.start_at - interval '15 minutes' then
    raise exception '尚未到预约开始时间，最早可提前 15 分钟开始';
  end if;
  update public.reservations set status = 'in_use' where id = p_booking_id;
  insert into public.usage_sessions (reservation_id, actual_start)
  values (p_booking_id, now())
  on conflict (reservation_id) do update set actual_start = excluded.actual_start, actual_end = null;
end;
$$;

