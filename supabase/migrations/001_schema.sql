-- Cell-room booking system schema
-- Run in the Supabase SQL Editor after creating a project.

create extension if not exists pgcrypto;
create extension if not exists btree_gist;

do $$ begin
  create type public.user_role as enum ('admin', 'member');
exception when duplicate_object then null; end $$;

do $$ begin
  create type public.user_status as enum ('pending', 'approved', 'suspended');
exception when duplicate_object then null; end $$;

do $$ begin
  create type public.booking_status as enum ('booked', 'in_use', 'completed', 'cancelled', 'no_show');
exception when duplicate_object then null; end $$;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text not null default '',
  display_name text not null default '',
  phone text not null default '',
  role public.user_role not null default 'member',
  status public.user_status not null default 'pending',
  approved_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.equipment (
  id bigint generated by default as identity primary key,
  name text not null unique,
  type text not null default '其他',
  location text not null default '',
  sort_order integer not null default 100,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.reservations (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  equipment_id bigint not null references public.equipment(id) on delete restrict,
  start_at timestamptz not null,
  end_at timestamptz not null,
  purpose text not null default '',
  status public.booking_status not null default 'booked',
  booked_by_name text not null default '',
  booked_by_email text not null default '',
  cancelled_at timestamptz,
  cancelled_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint reservations_time_order check (end_at > start_at),
  constraint reservations_same_local_day check (
    (start_at at time zone 'Asia/Shanghai')::date =
    (((end_at - interval '1 microsecond') at time zone 'Asia/Shanghai')::date)
  )
);

create table if not exists public.usage_sessions (
  id uuid primary key default gen_random_uuid(),
  reservation_id uuid not null unique references public.reservations(id) on delete cascade,
  actual_start timestamptz not null default now(),
  actual_end timestamptz,
  notes text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint usage_time_order check (actual_end is null or actual_end >= actual_start)
);

alter table public.reservations drop constraint if exists reservations_no_overlap;
alter table public.reservations
  add constraint reservations_no_overlap
  exclude using gist (
    equipment_id with =,
    tstzrange(start_at, end_at, '[)') with &&
  )
  where (status in ('booked', 'in_use'));

create index if not exists reservations_start_at_idx on public.reservations(start_at);
create index if not exists reservations_user_id_idx on public.reservations(user_id);
create index if not exists reservations_equipment_id_idx on public.reservations(equipment_id);
create index if not exists profiles_status_idx on public.profiles(status);

