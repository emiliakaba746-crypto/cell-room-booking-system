create or replace function public.promote_initial_admin()
returns boolean
language plpgsql
security definer
set search_path = public, auth
as $$
declare
  v_user_id uuid := auth.uid();
  v_email text;
  v_admin_exists boolean;
begin
  if v_user_id is null then
    return false;
  end if;

  select email into v_email from public.profiles where id = v_user_id;
  select exists (select 1 from public.profiles where role = 'admin' and status = 'approved') into v_admin_exists;

  if v_admin_exists or v_email is null or v_email = '' then
    return false;
  end if;

  update public.profiles
  set role = 'admin', status = 'approved', approved_at = now()
  where id = v_user_id and email = v_email;

  return found;
end;
$$;

